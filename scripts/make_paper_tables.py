"""Regenerate the paper's headline tables (III-VI) from the released runs.csv files alone.

  python scripts/make_paper_tables.py            -> docs/PAPER_TABLES.md

The numbers are computed here directly from results/*/runs.csv with the same definitions as the paper: p95 in ms (mean over
the 20 paired seeds), score W = max_i p95_i / D_i, effect sizes as paired differences to DRR with a t interval. The private
paper source is not needed. tools/claims_audit.py compares these numbers with the paper's own tables.
"""
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from claims_audit import CLS, ci_half, rd  # noqa: E402

TABLE_III = ["FIFO", "SP", "DRR", "RL-SP+DRR", "DR-DRR", "CQDRR", "FuzzyDRR", "RevenueDRR"]
TABLE_IV = {"SP": "SP", "RL-SP+DRR": "RL-SP+DRR", "DR-DRR": "DR-DRR", "DR-DRR, damped": "DR-DRR+damping", "CQDRR": "CQDRR",
            "FuzzyDRR": "FuzzyDRR", "RevenueDRR": "RevenueDRR"}
POINTS_IV = {"ON/OFF 0.95": "onoff|0.95", "ON/OFF 1.2": "onoff|1.2", "Poisson 0.95": "poisson|0.95", "Poisson 1.2": "poisson|1.2"}
POINTS_VI = {"ON/OFF 0.8": "onoff|0.8", "ON/OFF 0.95": "onoff|0.95", "ON/OFF 1.2": "onoff|1.2", "Poisson 0.95": "poisson|0.95",
             "Poisson 1.05": "poisson|1.05", "Poisson 1.2": "poisson|1.2"}
VI_COLS = ["DRR", "DR-DRR", "DR-DRR-backlog", "DR-DRR-hol", "DR-DRR+damping"]


def md(header, rows):
    return "\n".join(["| " + " | ".join(header) + " |", "|" + "---|" * len(header)] + ["| " + " | ".join(map(str, r)) + " |" for r in rows])


def build():
    e1, e1d, e14, e5, e8 = (rd(x) for x in ("E1", "E1D", "E14", "E5", "E8"))
    out = []
    g = e1[e1.point == "onoff|0.95"]
    rows = []
    for s in TABLE_III:
        a = g[g.scheduler == s]
        rows.append([s, f"{a.lat_p95.mean() * 1e3:.1f}", f"{a.vid_p95.mean() * 1e3:.1f}", f"{a.blk_p95.mean() * 1e3:.1f}", f"{a.W.mean():.3f}"])
    out += ["## Table III: ON/OFF at load 0.95, mean p95 (ms) and score W over 20 seeds", md(["scheduler", "latency", "video", "bulk", "W"], rows)]
    eff = pd.concat([e1, e1d], ignore_index=True)
    rows = []
    for label, s in TABLE_IV.items():
        r = [label]
        for point in POINTS_IV.values():
            gg = eff[eff.point == point]
            ref = gg[gg.scheduler == "DRR"].set_index("seed").sort_index().W
            dd = (gg[gg.scheduler == s].set_index("seed").sort_index().W - ref).dropna()
            r.append(f"{dd.mean():+.2f} ± {ci_half(dd):.2f}")
        rows.append(r)
    out += ["## Table IV: change in W relative to DRR (paired, 95 % t interval)", md(["scheduler", *POINTS_IV], rows)]
    p8 = e8[e8.point.str.contains("stress")]
    rows = []
    for s in TABLE_III:
        a, b = e5[e5.scheduler == s], p8[p8.scheduler == s]
        rows.append([s, *[f"{x:.1f}" if i == 0 else f"{x:.2f}" if i == 1 else f"{x:.3f}" for d in (a, b)
                          for i, x in enumerate((d.blk_starv_total.mean(), d.blk_tput.mean() / 1e6, d.jain.mean()))]])
    out += ["## Table V: stress test, shared and partitioned buffer (bulk starved s / bulk Mb/s / Jain)",
            md(["scheduler", "starved s", "Mb/s", "Jain", "starved s (part.)", "Mb/s (part.)", "Jain (part.)"], rows)]
    allr = pd.concat([e1[e1.scheduler.isin(["DRR", "DR-DRR"])], e1d, e14], ignore_index=True)
    rows = [[label, *[f"{allr[(allr.point == p) & (allr.scheduler == s)].W.mean():.3f}" for s in VI_COLS]] for label, p in POINTS_VI.items()]
    out += ["## Table VI: component ablation, mean W", md(["point", *VI_COLS], rows)]
    return "\n\n".join(out) + "\n"


if __name__ == "__main__":
    text = "# Paper tables regenerated from results/*/runs.csv\n\n(generated by scripts/make_paper_tables.py; do not edit)\n\n" + build()
    (ROOT / "docs" / "PAPER_TABLES.md").write_text(text, encoding="utf-8")
    print(text)
