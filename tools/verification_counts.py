"""Scheduler-by-scheduler counts of the exhaustive small-scope verification, generated from the test definitions.

  python tools/verification_counts.py          -> docs/VERIFICATION_COUNTS.md  (--check: fail if it is out of date)

Scope (tests/test_exhaustive.py): every trace of up to 4 packets on a grid of 3 arrival times x 3 classes x 2 sizes (7,315 traces),
simulated with 3 buffer settings = 21,945 cases per scheduler. Every scheduler variant keeps every invariant on every case; a
scheduler that has an independent reference implementation (tests/reference.py) must also match it packet for packet.
The one-off run with 5 packets (EXHAUSTIVE_N=5, 33,649 traces, 100,947 cases) is listed separately; it was made before the Modified
DRR variants existed and so covers 7 of the 9 reference configurations.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tests"))
import test_exhaustive as T  # noqa: E402
from conftest import ALL_SCHEDULERS  # noqa: E402

OUT = ROOT / "docs" / "VERIFICATION_COUNTS.md"
REF_OF = {"FIFO": ["FIFO"], "SP": ["SP"], "DRR": ["DRR q=500", "DRR q=1500", "DRR q=mixed"],
          "RL-SP+DRR": ["RL-SP r=0.25", "RL-SP r=1"], "MDRR-SP": ["MDRR-SP"], "MDRR-ALT": ["MDRR-ALT"]}
FIVE = 33_649 * 3
FIVE_REFS = ["FIFO", "SP", "DRR q=500", "DRR q=1500", "DRR q=mixed", "RL-SP r=0.25", "RL-SP r=1"]


def build():
    cases = len(T.TRACES) * len(T.CONFIGS)
    assert len(T.TRACES) == 7315 and cases == 21945, "run with the default EXHAUSTIVE_N=4"
    rows, ref_total, five_total = [], 0, 0
    for name in ALL_SCHEDULERS:
        refs = REF_OF.get(name, [])
        assert all(r in T.REFERENCES for r in refs), name
        n_ref = len(refs) * cases
        n_five = sum(1 for r in refs if r in FIVE_REFS) * FIVE
        ref_total += n_ref
        five_total += n_five
        rows.append((name, cases, len(refs), n_ref, n_five))
    assert set(sum(REF_OF.values(), [])) == set(T.REFERENCES), "a reference configuration is not mapped to a scheduler"
    return rows, cases, ref_total, five_total


def render():
    rows, cases, ref_total, five_total = build()
    out = ["# Exhaustive small-scope verification: counts by scheduler (generated by tools/verification_counts.py; do not edit)", "",
           __doc__.split("\n\n", 1)[1].strip(), "",
           "| scheduler | invariant cases (4-packet scope) | reference configs | reference comparisons (4-packet) | reference comparisons (5-packet one-off) |",
           "|---|---|---|---|---|"]
    for name, c, nr, n_ref, n_five in rows:
        out.append(f"| {name} | {c:,} | {nr} | {n_ref:,} | {n_five:,} |")
    out.append(f"| **total ({len(rows)} scheduler variants)** | **{cases * len(rows):,}** | {sum(r[2] for r in rows)} | **{ref_total:,}** | **{five_total:,}** |")
    out += ["", "Scope check: 3 arrival times x 3 classes x 2 sizes = 18 cells; all multisets of 0 to 4 cells = 7,315 traces; x 3 buffer "
            "settings (2,000 B shared, 4,500 B partitioned, 10^6 B shared) = 21,945 cases per scheduler. Five packets: 33,649 traces, 100,947 cases.", ""]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text(encoding="utf-8").replace("\r\n", "\n") == text else 1)
    OUT.write_text(text, encoding="utf-8")
    print(text)
